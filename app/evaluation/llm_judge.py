import json
import logging
from dataclasses import dataclass
from typing import Any

from app.evaluation.models import EvaluationResult
from app.providers.llm.base import (
    LLMProvider,
    LLMRequest,
)


logger = logging.getLogger(
    "contextops.evaluation.llm_judge"
)


# ============================================================
# JUDGE PROMPTS
# ============================================================

JUDGE_SYSTEM_PROMPT = """
You are an enterprise RAG evaluation judge.

Your task is to evaluate the quality of an answer generated by
an enterprise policy intelligence system.

Evaluate only the information provided in the evaluation input.

Return ONLY valid JSON with this exact structure:

{
  "correctness_score": 0,
  "grounding_score": 0,
  "citation_score": 0,
  "reason": "..."
}

Scoring:

correctness_score:
    0 = completely incorrect
    1 = mostly incorrect
    2 = partially correct
    3 = mostly correct
    4 = fully correct

grounding_score:
    0 = unsupported by provided context
    1 = weakly supported
    2 = partially supported
    3 = strongly supported
    4 = fully supported by the provided context

citation_score:
    0 = citations missing or unusable
    1 = citations present but weak/incomplete
    2 = citations mostly appropriate
    3 = citations strongly support the answer
    4 = citations appropriately support the answer completely

Do not reward an answer for information that is not supported
by the provided context.
""".strip()


# ============================================================
# RESULT MODEL
# ============================================================

@dataclass(frozen=True)
class LLMJudgeResult:
    """
    Result returned by the LLM-as-a-judge evaluator.
    """

    correctness_score: float

    grounding_score: float

    citation_score: float

    reason: str

    metadata: dict[str, Any]


# ============================================================
# JUDGE
# ============================================================

class LLMJudge:
    """
    LLM-as-a-judge evaluator for ContextOps.

    The judge uses the application's LLMProvider abstraction
    instead of directly depending on a specific model provider.
    """

    def __init__(
        self,
        llm_provider: LLMProvider,
    ) -> None:
        self.llm_provider = llm_provider

    # ========================================================
    # PUBLIC API
    # ========================================================

    async def evaluate(
        self,
        *,
        evaluation_result: EvaluationResult,
        context: str,
        citations: list[dict[str, Any]] | None = None,
    ) -> LLMJudgeResult:
        """
        Evaluate one generated answer.

        Args:
            evaluation_result:
                Result produced by EvaluationRunner.

            context:
                Retrieved/contextualized evidence used by the
                query workflow.

            citations:
                Citations generated by the query workflow.
        """

        prompt = self._build_user_prompt(
            evaluation_result=evaluation_result,
            context=context,
            citations=citations or [],
        )

        request = LLMRequest(
            system_prompt=JUDGE_SYSTEM_PROMPT,
            user_prompt=prompt,
            context=None,
        )

        try:
            response = await self.llm_provider.agenerate(
                request
            )

            return self._parse_response(
                response.content
            )

        except Exception:
            logger.exception(
                "ContextOps LLM judge failed."
            )
            raise

    # ========================================================
    # PROMPT CONSTRUCTION
    # ========================================================

    def _build_user_prompt(
        self,
        *,
        evaluation_result: EvaluationResult,
        context: str,
        citations: list[dict[str, Any]],
    ) -> str:
        """
        Construct a deterministic evaluation prompt.
        """

        expected_answer = (
            evaluation_result.expected_answer
            or "No reference answer was provided."
        )

        citations_json = json.dumps(
            citations,
            ensure_ascii=False,
            default=str,
        )

        return f"""
Evaluate the following ContextOps RAG response.

QUESTION:
{evaluation_result.question}

EXPECTED ANSWER:
{expected_answer}

GENERATED ANSWER:
{evaluation_result.answer}

RETRIEVED CONTEXT:
{context}

GENERATED CITATIONS:
{citations_json}

Evaluate:

1. Is the generated answer correct relative to the
   expected answer and retrieved context?

2. Is the generated answer grounded in the retrieved context?

3. Do the citations appropriately support the generated answer?

Return ONLY the required JSON object.
""".strip()

    # ========================================================
    # RESPONSE PARSING
    # ========================================================

    def _parse_response(
        self,
        content: str,
    ) -> LLMJudgeResult:
        """
        Parse and validate the judge response.
        """

        if not isinstance(content, str):
            raise ValueError(
                "LLM judge response must be a string."
            )

        cleaned_content = content.strip()

        if not cleaned_content:
            raise ValueError(
                "LLM judge returned an empty response."
            )

        try:
            payload = json.loads(
                cleaned_content
            )
        except json.JSONDecodeError as exc:
            raise ValueError(
                "LLM judge returned invalid JSON."
            ) from exc

        if not isinstance(payload, dict):
            raise ValueError(
                "LLM judge response must be a JSON object."
            )

        correctness_score = self._parse_score(
            payload.get("correctness_score"),
            field_name="correctness_score",
        )

        grounding_score = self._parse_score(
            payload.get("grounding_score"),
            field_name="grounding_score",
        )

        citation_score = self._parse_score(
            payload.get("citation_score"),
            field_name="citation_score",
        )

        reason = payload.get(
            "reason",
            "",
        )

        if not isinstance(reason, str):
            raise ValueError(
                "LLM judge reason must be a string."
            )

        return LLMJudgeResult(
            correctness_score=correctness_score,
            grounding_score=grounding_score,
            citation_score=citation_score,
            reason=reason.strip(),
            metadata={
                "evaluator": "llm_judge",
            },
        )

    # ========================================================
    # SCORE VALIDATION
    # ========================================================

    def _parse_score(
        self,
        value: object,
        *,
        field_name: str,
    ) -> float:
        """
        Validate an individual 0-4 judge score.
        """

        if isinstance(value, bool):
            raise ValueError(
                f"{field_name} must be a numeric score."
            )

        if not isinstance(
            value,
            (int, float),
        ):
            raise ValueError(
                f"{field_name} must be numeric."
            )

        score = float(value)

        if score < 0 or score > 4:
            raise ValueError(
                f"{field_name} must be between 0 and 4."
            )

        return score